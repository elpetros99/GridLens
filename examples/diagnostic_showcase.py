from __future__ import annotations

import argparse
import copy
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import pandapower.networks as pn

from batched_powerflow import (
    CpuNewtonOptions,
    complete_diagnostic_security_analysis,
    explain_powerflow,
    from_pandapower,
    solve_batch_cpu_sparse,
)
from batched_powerflow.contingency import Contingency, Outage, apply_contingency
from batched_powerflow.dc_screening import score_contingencies_dc
from batched_powerflow.pandapower_adapter import PandapowerBuildOptions


BUILD = PandapowerBuildOptions(check_connectivity=False, preconditioner="none")


def _clip(text: str, max_lines: int) -> str:
    lines = text.strip().splitlines()
    if len(lines) <= max_lines:
        return "\n".join(lines)
    return "\n".join(lines[:max_lines] + ["", f"... clipped {len(lines) - max_lines} lines ..."])


def _base_solved_case() -> str:
    net = pn.case14()
    model = from_pandapower(net, options=BUILD)
    result = solve_batch_cpu_sparse(model, options=CpuNewtonOptions(max_iterations=15, tolerance=1e-10))
    report = explain_powerflow(net, model=model, result=result)
    return report.to_markdown()


def _missing_slack_case() -> str:
    net = pn.case14()
    net.ext_grid["in_service"] = False
    if hasattr(net, "gen") and "slack" in net.gen:
        net.gen["slack"] = False
    report = explain_powerflow(net)
    return report.to_markdown()


def _islanded_contingency_case() -> str:
    net = pn.case33bw()
    contingency = Contingency((Outage("line", 0),))
    work = apply_contingency(net, contingency)
    model = from_pandapower(work, options=BUILD)
    result = solve_batch_cpu_sparse(model, options=CpuNewtonOptions(max_iterations=10, tolerance=1e-10))
    dc_result = next(score_contingencies_dc(net, [contingency], options=BUILD, chunk_size=1))
    report = explain_powerflow(work, model=model, result=result, dc_result=dc_result, contingency=contingency)
    return report.to_markdown()


def _zero_impedance_case() -> str:
    net = pn.case14()
    line = int(net.line.index[0])
    net.line.at[line, "length_km"] = 0.0
    net.line.at[line, "r_ohm_per_km"] = 0.0
    net.line.at[line, "x_ohm_per_km"] = 0.0
    report = explain_powerflow(net)
    return report.to_markdown()


def _non_converged_case() -> str:
    net = pn.case14()
    model = from_pandapower(net, options=BUILD)
    result = solve_batch_cpu_sparse(model, options=CpuNewtonOptions(max_iterations=0, tolerance=1e-12))
    report = explain_powerflow(net, model=model, result=result)
    return report.to_markdown()


def _complete_n1_security_case() -> str:
    net = pn.case14()
    report = complete_diagnostic_security_analysis(
        net,
        k=1,
        elements=("line",),
        top_n=3,
        ac_mode="top",
        build_options=BUILD,
        cpu_options=CpuNewtonOptions(max_iterations=15, tolerance=1e-9),
    )
    return report.to_markdown()


def _complete_n2_security_case() -> str:
    net = pn.case14()
    report = complete_diagnostic_security_analysis(
        net,
        k=2,
        elements=("line",),
        n1_pool=6,
        top_n=5,
        max_cases=None,
        ac_mode="top",
        build_options=BUILD,
        cpu_options=CpuNewtonOptions(max_iterations=15, tolerance=1e-9),
    )
    return report.to_markdown()


def run_showcase(max_lines: int) -> str:
    examples = [
        ("1. Solved Base Case With Stability Indicators", _base_solved_case()),
        ("2. Missing Slack / Reference Source", _missing_slack_case()),
        ("3. Islanding Contingency With Causal Explanation", _islanded_contingency_case()),
        ("4. Zero-Impedance Data Defect", _zero_impedance_case()),
        ("5. Non-Converged Solve With Residual Hot Spots", _non_converged_case()),
        ("6. Complete N-1 Diagnostic Security Verdict", _complete_n1_security_case()),
        ("7. N-2 Risk-Pool Diagnostic Security Verdict", _complete_n2_security_case()),
    ]
    lines = [
        "# Diagnostic Showcase Outputs",
        "",
        "These examples were generated by running the current code against pandapower networks.",
        "",
    ]
    for title, body in examples:
        lines.extend([f"## {title}", "", _clip(body, max_lines), ""])
    return "\n".join(lines)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Generate a diagnostics showcase report from real pandapower cases.")
    parser.add_argument("--out", default="benchmark_results/diagnostic_showcase.md")
    parser.add_argument("--max-lines", type=int, default=70)
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    output = run_showcase(args.max_lines)
    path = ROOT / args.out
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(output, encoding="utf-8")
    print(path)


if __name__ == "__main__":
    main()
